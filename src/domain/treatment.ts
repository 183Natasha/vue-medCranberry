/**
 * Следующий этап по схеме для пары (этап, эффект).
 * Пустая строка — курс завершён (оценка не предусмотрена).
 */
export function nextTreatmentStage(stage: string, effect: string): string {
  switch (stage) {
    case 'monotherapy':
      return effect === 'full' ? 'maintain' : effect === 'partial' ? 'dose_max' : 'switch'
    case 'dose_max':
      return effect === 'full' ? 'maintain' : 'switch'
    case 'switch':
      return effect === 'full' ? 'maintain' : 'pregabalin'
    case 'pregabalin':
      return effect === 'full' ? 'maintain' : 'augmentation'
    case 'augmentation':
      return effect === 'full' ? 'maintain' : 'reserve'
    case 'reserve':
      return effect === 'full' ? 'maintain' : effect === 'partial' ? 'reserve' : 'resistant'
    // Поддерживающая фаза: полный эффект — продолжение приёма; рецидив — корректировка терапии
    case 'maintain':
      return effect === 'full' ? 'maintain' : effect === 'partial' ? 'dose_max' : 'switch'
    default:
      return ''
  }
}

