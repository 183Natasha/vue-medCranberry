// Определения шкал для прохождения в виде опросника
import type { TestType } from './store'

export interface ScaleOption {
  label: string
  score: number
}

export interface ScaleQuestion {
  text: string
  subscale?: 'A' | 'D' // для HADS: подшкала тревоги / депрессии
  options: ScaleOption[]
}

export interface ScaleResultDef {
  type: TestType
  title: string
  // индексы вопросов опросника, входящих в результат
  pick: (answers: number[]) => number
}

export interface ScaleDef {
  key: string
  title: string
  description: string
  questions: ScaleQuestion[]
  results: ScaleResultDef[]
}

