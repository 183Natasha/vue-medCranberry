export const SCALES_BY_TYPE: Record<string, string> = {}
for (const def of Object.values(SCALES)) {
  for (const r of def.results) {
    if (!SCALES_BY_TYPE[r.type]) SCALES_BY_TYPE[r.type] = def.key
  }
}

function sum(answers: number[], subscale: 'A' | 'D', questions: ScaleQuestion[] = SCALES.HADS.questions): number {
  return answers.reduce((s, v, i) => (questions[i]?.subscale === subscale ? s + v : s), 0)
}

